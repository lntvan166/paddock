import { expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { coreDowngradeRefusal, parseCommittedGeneration } from "../scripts/protocol-guard";

const header = readFileSync("src/shared/herdr-core-api.d.ts", "utf8").split("\n").slice(0, 8).join("\n");

test("the committed core API names generation 1 and herdr-core's version", () => {
  expect(header).toContain("// generation: 1");
  expect(header).toContain("// herdr-core: 0.1.");
});

test("the committed core API is never hand-edited", () => {
  expect(header).toContain("generated by scripts/gen-core-types.ts");
});

test("regenerating refuses a generation lower than the committed one", () => {
  expect(parseCommittedGeneration(header)).toBe(1);
  expect(coreDowngradeRefusal(1, 2, false)).toContain("HERDR_ALLOW_DOWNGRADE");
  expect(coreDowngradeRefusal(1, 2, true)).toBeNull();
  expect(coreDowngradeRefusal(2, 1, false)).toBeNull();
  expect(coreDowngradeRefusal(1, null, false)).toBeNull();
});
