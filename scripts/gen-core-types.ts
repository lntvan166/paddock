// Generates src/shared/herdr-core-api.d.ts from the installed herdr-core's own
// schema (`hc schema`, an OpenRPC document). Run via `make types`. Never
// hand-edit the output.
import { ALLOW_DOWNGRADE_ENV, coreDowngradeRefusal, parseCommittedGeneration } from "./protocol-guard";

// Both overridable so the downgrade guard can be exercised without a second
// install, the same convention as gen-herdr-types.ts.
const HC_BIN = process.env.HC_BIN ?? "hc";
const OUT = process.env.HERDR_CORE_TYPES_OUT ?? "src/shared/herdr-core-api.d.ts";

const proc = Bun.spawn([HC_BIN, "schema"], { stdout: "pipe", stderr: "pipe" });
const raw = await new Response(proc.stdout).text();
if ((await proc.exited) !== 0) {
  throw new Error(`hc schema failed: ${await new Response(proc.stderr).text()}`);
}
const doc = JSON.parse(raw);
const schemas: Record<string, any> = doc.components.schemas;
const version: string = doc.info.version;
const gen = /Protocol generation (\d+)/.exec(doc.info.description ?? "");
if (!gen) throw new Error("hc schema: info.description does not name a protocol generation");
const generation = Number(gen[1]);

const existing = Bun.file(OUT);
const committed = (await existing.exists()) ? parseCommittedGeneration(await existing.text()) : null;
const refusal = coreDowngradeRefusal(generation, committed, Boolean(process.env[ALLOW_DOWNGRADE_ENV]));
if (refusal) {
  console.error(refusal);
  process.exit(1);
}

// The schemas paddock reads; anything they $ref is pulled in transitively.
const WANTED = ["Terminal", "Status", "Foreground", "ReadResult", "ListResult", "SubscribeResult", "HelloResult", "DocGetResult"];
const prefix = (n: string) => (n.startsWith("Core") ? n : `Core${n}`);

function ts(s: any): string {
  if (s === true || s === undefined) return "unknown";
  if (s.$ref) return prefix(s.$ref.split("/").pop());
  if (s.anyOf) return s.anyOf.map(ts).join(" | ");
  if (Array.isArray(s.type)) return s.type.map((t: string) => ts({ ...s, type: t })).join(" | ");
  switch (s.type) {
    case "string": return "string";
    case "integer": case "number": return "number";
    case "boolean": return "boolean";
    case "null": return "null";
    case "array": return `${ts(s.items)}[]`;
    case "object":
      if (s.properties) return objectBody(s);
      return `Record<string, ${ts(s.additionalProperties)}>`;
    default: return "unknown";
  }
}

function objectBody(s: any): string {
  const required = new Set<string>(s.required ?? []);
  const fields = Object.entries<any>(s.properties).map(([k, v]) => {
    const doc = v.description ? `  /** ${String(v.description).replace(/\*\//g, "*\\/").replace(/\n/g, " ")} */\n` : "";
    return `${doc}  ${k}${required.has(k) ? "" : "?"}: ${ts(v)};`;
  });
  return `{\n${fields.join("\n")}\n}`;
}

function refs(s: any, into: Set<string>) {
  if (s && typeof s === "object") {
    if (typeof s.$ref === "string") into.add(s.$ref.split("/").pop());
    for (const v of Object.values(s)) refs(v, into);
  }
}
const needed = new Set<string>(WANTED);
for (const n of needed) {
  if (!schemas[n]) throw new Error(`hc schema has no ${n}`);
  refs(schemas[n], needed);
}

const decls = [...needed].sort().map((n) => {
  const s = schemas[n];
  const doc = s.description ? `/** ${String(s.description).replace(/\n/g, " ")} */\n` : "";
  return `${doc}export interface ${prefix(n)} ${objectBody(s)}`;
});

// The event union comes from herdr-core's schema/README.md "Events" table, not
// from `hc schema`, which does not describe notifications. Modelled as stated
// there; CoreUnknownEvent keeps a type added later representable, because the
// API only grows. `machine` appears on events relayed from an added machine.
const out = `// generated by scripts/gen-core-types.ts — do not edit.
// generation: ${generation}
// herdr-core: ${version}
// Source: \`hc schema\`; the event union follows herdr-core's schema/README.md "Events".

export const CoreGeneration = ${generation} as const;

${decls.join("\n\n")}

/** Fields every \`event\` notification's params carry. */
export interface CoreEventBase {
  seq: number;
  /** Absent on \`doc\` events. \`machine/t7\` for a terminal on an added machine. */
  terminal?: string;
  machine?: string;
}

export type CoreLostReason = { reason: string | null; exit_code: number | null; signal: number | null; finished_ms: null };
export type CoreFinishedData = { reason: string | null; exit_code: number | null; signal: number | null; finished_ms: number };

export type CoreEvent =
  | (CoreEventBase & { type: "created"; data: CoreTerminal })
  | (CoreEventBase & { type: "lost"; data: CoreLostReason })
  | (CoreEventBase & { type: "restarted"; data: CoreTerminal })
  | (CoreEventBase & { type: "keep"; data: { keep: boolean } })
  | (CoreEventBase & { type: "finished"; data: CoreFinishedData })
  | (CoreEventBase & { type: "removed"; data: Record<string, never> })
  | (CoreEventBase & { type: "status"; data: { status: CoreStatus | null; records: Record<string, CoreStatus>; reported: boolean } })
  | (CoreEventBase & { type: "turn"; data: { turn: number; state: string } })
  | (CoreEventBase & { type: "title"; data: { title: string } })
  | (CoreEventBase & { type: "labels"; data: { labels: Record<string, string>; record?: CoreTerminal } })
  | (CoreEventBase & { type: "size"; data: { cols: number; rows: number } })
  | (CoreEventBase & { type: "foreground"; data: CoreForeground | null })
  | (CoreEventBase & { type: "doc"; data: { name: string; version: number } });

/** A type this generation does not know yet. Tolerated, never an error. */
export interface CoreUnknownEvent extends CoreEventBase {
  type: string;
  data: unknown;
}

/** The \`missed\` notification: a fresh snapshot; ignore events with seq not above it. */
export interface CoreMissed {
  seq: number;
  terminals: CoreTerminal[];
}

export interface CoreHeartbeat {
  seq: number;
}
`;

await Bun.write(OUT, out);
console.log(`wrote ${OUT} (generation ${generation}, herdr-core ${version}, ${needed.size} schemas)`);
